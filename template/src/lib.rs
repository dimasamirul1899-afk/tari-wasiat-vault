//! Wasiat — a digital inheritance vault on Tari Ootle.
//!
//! The problem: crypto has no will. If the holder of a wallet disappears, the
//! funds are locked forever — nobody can prove the owner is gone, and nobody
//! can prove who should inherit. A will on paper does not help either: it
//! names an heir, but it cannot move the coins, and it trusts whoever holds
//! the keys.
//!
//! Wasiat puts the will on chain. The owner locks XTM in a vault, names a
//! beneficiary, and picks an inactivity period in epochs. As long as the owner
//! is around, they send a `heartbeat` every so often and the deadline keeps
//! moving. If the owner goes silent for the whole inactivity period, the
//! beneficiary — and only the beneficiary — can `claim` the entire vault.
//! The owner can change their mind at any time before a claim and `cancel`
//! the vault, taking the funds back in full.
//!
//! Rules enforced by the template itself, never just by the UI:
//! - Only the beneficiary can claim, and only after the inactivity deadline
//!   has passed without a heartbeat. An early claim is refused.
//! - Only the owner can send a heartbeat or cancel.
//! - A claim or a cancel moves the WHOLE vault: no partial amounts, no dust.
//! - Once claimed or cancelled, the vault is finished: no second claim, no
//!   heartbeat, no cancel.

use tari_template_lib::prelude::*;

#[template]
mod wasiat_vault {
    use super::*;

    pub struct WasiatVault {
        /// The owner: the key that created the vault. Only this key can send a
        /// heartbeat or cancel. Recorded as a public key so the check is the
        /// engine's transaction signer, not an address anyone could pass in.
        owner: RistrettoPublicKeyBytes,
        /// The owner's account, where a cancellation refunds to. Supplied at
        /// creation; the owner is the only party hurt by supplying a wrong one.
        owner_account: ComponentAddress,
        /// The beneficiary: fixed at creation, never changeable. Only this key
        /// can claim the vault.
        beneficiary: RistrettoPublicKeyBytes,
        /// The beneficiary's account, where a claim pays to. Supplied at
        /// creation; the beneficiary is the only party hurt by supplying a
        /// wrong one.
        beneficiary_account: ComponentAddress,
        /// The locked inheritance, as locked at creation. Never changes;
        /// payouts always move the whole vault, so this is also the exact
        /// amount any claim or cancel sends.
        amount: Amount,
        /// How many epochs of owner silence must pass before the beneficiary
        /// may claim. An epoch on mainnet is about 20 minutes.
        inactivity_epochs: u64,
        /// Epoch of the creation, or of the most recent heartbeat. The
        /// beneficiary may claim once the chain reaches this epoch plus
        /// `inactivity_epochs`.
        last_heartbeat_epoch: u64,
        state: VaultState,
        vault: Vault,
    }

    /// The vault lifecycle. Only one transition is allowed out of Active;
    /// every transition is enforced inside the template, never just by the UI.
    /// (Encode/Decode impls are generated by the #[template] macro.)
    #[derive(Debug, Clone, Copy, PartialEq, Eq)]
    pub enum VaultState {
        Active,
        Claimed,
        Cancelled,
    }

    impl WasiatVault {
        /// Creates a vault and locks the funds in the component vault.
        ///
        /// The caller becomes the owner. `bucket` must be TARI and non-empty;
        /// the inactivity period must be at least one epoch; the beneficiary
        /// must differ from the owner.
        pub fn create(
            bucket: Bucket,
            beneficiary: RistrettoPublicKeyBytes,
            beneficiary_account: ComponentAddress,
            inactivity_epochs: u64,
            owner_account: ComponentAddress,
        ) -> Component<Self> {
            assert!(bucket.resource_address() == TARI_TOKEN, "vault funds must be in TARI");
            let amount = bucket.amount();
            assert!(amount.is_positive(), "amount must be more than zero");
            assert!(
                inactivity_epochs > 0,
                "inactivity period must be at least one epoch"
            );
            let owner = CallerContext::transaction_signer_public_key();
            assert!(beneficiary != owner, "beneficiary must differ from the owner");

            let vault = Vault::new_empty(TARI_TOKEN);
            vault.deposit(bucket);

            // Every method is callable by anyone; the owner / beneficiary checks
            // live inside the methods, against the engine's transaction signer.
            let access_rules = ComponentAccessRules::new()
                .method("heartbeat", rule![allow_all])
                .method("claim", rule![allow_all])
                .method("cancel", rule![allow_all])
                .method("get_state", rule![allow_all])
                .method("get_details", rule![allow_all]);

            let last_heartbeat_epoch = Consensus::current_epoch();

            emit_event("VaultCreated", metadata![
                "amount" => amount,
                "inactivity_epochs" => inactivity_epochs,
                "claimable_epoch" => last_heartbeat_epoch.saturating_add(inactivity_epochs),
                "state" => String::from("Active"),
            ]);

            Component::new(Self {
                owner,
                owner_account,
                beneficiary,
                beneficiary_account,
                amount,
                inactivity_epochs,
                last_heartbeat_epoch,
                state: VaultState::Active,
                vault,
            })
            .with_access_rules(access_rules)
            .create()
        }

        /// Proves the owner is still here. Owner only, and only while Active.
        /// Moves the claimable epoch forward by `inactivity_epochs` from now.
        pub fn heartbeat(&mut self) {
            assert!(self.state == VaultState::Active, "vault is not Active");
            assert!(
                CallerContext::transaction_signer_public_key() == self.owner,
                "only the owner can send a heartbeat"
            );
            self.last_heartbeat_epoch = Consensus::current_epoch();
            emit_event("Heartbeat", metadata![
                "claimable_epoch" => self.claimable_epoch(),
                "state" => String::from("Active"),
            ]);
        }

        /// Claims the vault. Beneficiary only, only while Active, and only
        /// once the chain has reached the claimable epoch (the last heartbeat
        /// plus the inactivity period). Pays the entire vault to the
        /// beneficiary's account.
        pub fn claim(&mut self) {
            assert!(self.state == VaultState::Active, "vault is not Active");
            assert!(
                CallerContext::transaction_signer_public_key() == self.beneficiary,
                "only the beneficiary can claim"
            );
            assert!(
                Consensus::current_epoch() >= self.claimable_epoch(),
                "inactivity deadline has not been reached"
            );
            let balance = self.vault.balance();
            let bucket = self.vault.withdraw(balance);
            ComponentManager::get(self.beneficiary_account).invoke("deposit", args![bucket]);
            self.state = VaultState::Claimed;
            emit_event("Claimed", metadata![
                "amount" => balance,
                "state" => String::from("Claimed"),
            ]);
        }

        /// Cancels the vault. Owner only, and only while Active. Refunds the
        /// entire vault to the owner's account.
        pub fn cancel(&mut self) {
            assert!(self.state == VaultState::Active, "vault is not Active");
            assert!(
                CallerContext::transaction_signer_public_key() == self.owner,
                "only the owner can cancel"
            );
            let balance = self.vault.balance();
            let bucket = self.vault.withdraw(balance);
            ComponentManager::get(self.owner_account).invoke("deposit", args![bucket]);
            self.state = VaultState::Cancelled;
            emit_event("Cancelled", metadata![
                "amount" => balance,
                "state" => String::from("Cancelled"),
            ]);
        }

        /// Returns the current state as a string: Active, Claimed, or
        /// Cancelled.
        pub fn get_state(&self) -> String {
            String::from(Self::state_name(self.state))
        }

        /// Returns (state, amount, vault balance, owner, beneficiary,
        /// inactivity epochs, last heartbeat epoch, claimable epoch).
        pub fn get_details(
            &self,
        ) -> (
            String,
            Amount,
            Amount,
            RistrettoPublicKeyBytes,
            RistrettoPublicKeyBytes,
            u64,
            u64,
            u64,
        ) {
            (
                String::from(Self::state_name(self.state)),
                self.amount,
                self.vault.balance(),
                self.owner,
                self.beneficiary,
                self.inactivity_epochs,
                self.last_heartbeat_epoch,
                self.claimable_epoch(),
            )
        }

        /// The first epoch the beneficiary may claim: the last heartbeat plus
        /// the inactivity period.
        fn claimable_epoch(&self) -> u64 {
            self.last_heartbeat_epoch.saturating_add(self.inactivity_epochs)
        }

        /// Private helper: the state's name. Kept private so the template
        /// dispatcher ignores it (only public methods become on-chain calls).
        fn state_name(state: VaultState) -> &'static str {
            match state {
                VaultState::Active => "Active",
                VaultState::Claimed => "Claimed",
                VaultState::Cancelled => "Cancelled",
            }
        }
    }
}
